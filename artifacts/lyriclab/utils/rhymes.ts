// This catches suffix-matching false positives (e.g. "roast" → "ast" → "last").

export const HINT_PHRASES: Array<(word: string, rhyme: string) => string> = [
  (w, r) => `Stuck? Run '${w}' into '${r}' — close that bar`,
  (w, r) => `OG says: bridge '${w}' with '${r}', make it land`,
  (w, r) => `'${w}' set it up. '${r}' brings it home.`,
  (w, r) => `Need a rhyme? '${w}' × '${r}' — that combo still fresh`,
  (w, r) => `Flip '${w}' on '${r}' — keep that pocket tight`,
  (w, r) => `Can't find the end? '${w}' lands nice on '${r}'`,
  (w, r) => `Hook for '${w}': try '${r}' to close it out`,
];

export function pickHintPhrase(word: string, rhyme: string): string {
  const fn = HINT_PHRASES[Math.floor(Math.random() * HINT_PHRASES.length)]!;
  return fn(word, rhyme);
}

