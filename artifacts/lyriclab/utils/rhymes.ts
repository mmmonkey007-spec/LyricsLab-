/**
 * Bidirectional rhyme validation.
 * Returns true only if `rhyme` appears in suggestRhymes(word) OR
 * `word` appears in suggestRhymes(rhyme). Using both directions means
 * suffix-matching false positives (e.g. "roast"→"ast"→"last") are caught
 * because the reverse lookup ("last"→suggestRhymes→no "roast") fails too.
 */
export function isValidRhymePair(word: string, rhyme: string): boolean {
  const w = word.toLowerCase().replace(/[^a-z]/g, "");
  const r = rhyme.toLowerCase().replace(/[^a-z]/g, "");
  if (!w || !r || w === r) return false;
  if (suggestRhymes(w).includes(r)) return true;
  if (suggestRhymes(r).includes(w)) return true;
  return false;
}
